#!/usr/bin/env node
// ============================================
// WHAT THIS FILE DOES (plain English):
// Scans the demo drop folders (profile pics + per-person story media) and
// rewrites demo-media.generated.ts with require() lines Metro can bundle.
// Run after you drop or replace files: node apps/mobile/scripts/sync-demo-media.mjs
// ============================================
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const mobileRoot = path.resolve(__dirname, '..');
const demoRoot = path.join(mobileRoot, 'assets', 'demo');
const outFile = path.join(mobileRoot, 'data', 'fixtures', 'demo-media.generated.ts');

/** Folder slug → person id used in fixtures (ids stay stable; names changed). */
const PROFILE_FILES = {
  brant: 'me',
  jade: 'maya',
  kelton: 'devon',
  janna: 'ines',
  levi: 'kit',
  ben: 'theo',
  ceci: 'nour',
  jordyn: 'jordyn'
};

const STORY_FOLDERS = {
  brant: 'me',
  jade: 'maya',
  kelton: 'devon',
  levi: 'kit',
  janna: 'ines'
};

const IMAGE_EXT = new Set(['.jpg', '.jpeg', '.png', '.webp']);
const VIDEO_EXT = new Set(['.mp4', '.mov']);

// Metro's asset resolver is case-sensitive and only knows lowercase
// extensions (e.g. it looks for ".mov", not ".MOV"). Phones often export files
// with uppercase extensions, so we rename any media file to a lowercase
// extension on disk before generating the require() lines.
function normalizeExtensions(dir) {
  if (!fs.existsSync(dir)) return;
  for (const file of fs.readdirSync(dir)) {
    const ext = path.parse(file).ext;
    const lower = ext.toLowerCase();
    if (ext === lower) continue;
    if (!IMAGE_EXT.has(lower) && !VIDEO_EXT.has(lower)) continue;
    const from = path.join(dir, file);
    const to = path.join(dir, path.parse(file).name + lower);
    if (!fs.existsSync(to)) fs.renameSync(from, to);
  }
}

function findProfileFile(slug) {
  const dir = path.join(demoRoot, 'profile-pics');
  if (!fs.existsSync(dir)) return null;
  for (const ext of IMAGE_EXT) {
    const file = `${slug}${ext}`;
    if (fs.existsSync(path.join(dir, file))) return file;
  }
  // Also allow slug with capital letters etc. — match case-insensitive stem
  const match = fs.readdirSync(dir).find((f) => {
    const stem = path.parse(f).name.toLowerCase();
    const ext = path.parse(f).ext.toLowerCase();
    return stem === slug && IMAGE_EXT.has(ext);
  });
  return match ?? null;
}

function listStoryFiles(slug) {
  const dir = path.join(demoRoot, 'stories', slug);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => {
      const ext = path.parse(f).ext.toLowerCase();
      return IMAGE_EXT.has(ext) || VIDEO_EXT.has(ext);
    })
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
}

function captionFor(dir, file) {
  const stem = path.parse(file).name;
  const txt = path.join(dir, `${stem}.txt`);
  if (!fs.existsSync(txt)) return null;
  return fs.readFileSync(txt, 'utf8').trim().split('\n')[0] ?? null;
}

// Lowercase any uppercase media extensions before scanning.
normalizeExtensions(path.join(demoRoot, 'profile-pics'));
for (const slug of Object.keys(STORY_FOLDERS)) {
  normalizeExtensions(path.join(demoRoot, 'stories', slug));
}

const profileLines = [];
for (const [slug, personId] of Object.entries(PROFILE_FILES)) {
  const file = findProfileFile(slug);
  if (!file) continue;
  const rel = `../../assets/demo/profile-pics/${file}`;
  profileLines.push(`  '${personId}': require('${rel}'),`);
}

const storyBlocks = [];
for (const [slug, personId] of Object.entries(STORY_FOLDERS)) {
  const files = listStoryFiles(slug);
  if (files.length === 0) continue;
  const dir = path.join(demoRoot, 'stories', slug);
  const items = [];
  for (const file of files) {
    const ext = path.parse(file).ext.toLowerCase();
    // Photos and videos both become slides. The story viewer plays videos
    // with expo-video and shows photos with <Image>.
    const type = VIDEO_EXT.has(ext) ? 'video' : 'photo';
    const rel = `../../assets/demo/stories/${slug}/${file}`;
    const caption = captionFor(dir, file);
    const cap = caption ? `, caption: ${JSON.stringify(caption)}` : '';
    items.push(`    { type: '${type}', source: require('${rel}')${cap} }`);
  }
  if (items.length === 0) continue;
  storyBlocks.push(`  '${personId}': [\n${items.join(',\n')}\n  ]`);
}

const contents = `// AUTO-GENERATED by apps/mobile/scripts/sync-demo-media.mjs — do not edit by hand.
// Drop files into apps/mobile/assets/demo/ then re-run the script.
import type { ImageSourcePropType } from 'react-native';

export type DemoStoryMedia = {
  type: 'photo' | 'video';
  source: ImageSourcePropType;
  caption?: string;
};

export const PROFILE_PHOTOS: Partial<Record<string, ImageSourcePropType>> = {
${profileLines.join('\n')}
};

export const STORY_MEDIA: Partial<Record<string, DemoStoryMedia[]>> = {
${storyBlocks.join(',\n')}
};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, contents);
console.log(`Wrote ${path.relative(process.cwd(), outFile)}`);
console.log(`  profile photos: ${profileLines.length}`);
console.log(`  story authors with media: ${storyBlocks.length}`);
